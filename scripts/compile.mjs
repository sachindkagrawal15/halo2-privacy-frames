// Compiles the contracts with solc-js 0.8.28 (the version EF's HegotaSupport pins) and writes
// contracts/out/<Name>.json with abi, bytecode and link references.
//
//   node scripts/compile.mjs
// The Halo2 verifier is compiled too when circuits/build/GhostVerifier.sol exists (`ghost-cli setup`).
import solc from "solc";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "contracts/out");

function findImports(importPath) {
  for (const base of [path.join(root, "contracts"), path.join(root, "node_modules")]) {
    const file = path.join(base, importPath);
    if (existsSync(file)) return { contents: readFileSync(file, "utf8") };
  }
  return { error: `not found: ${importPath}` };
}

function compile(sources, settings, transform = (source) => source) {
  const input = {
    language: "Solidity",
    sources: Object.fromEntries(
      Object.entries(sources).map(([name, file]) => [name, { content: transform(readFileSync(file, "utf8")) }]),
    ),
    settings: {
      evmVersion: "cancun",
      ...settings,
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.bytecode.linkReferences", "evm.deployedBytecode.object"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
  const errors = (output.errors ?? []).filter((e) => e.severity === "error");
  for (const e of output.errors ?? []) if (e.severity !== "error" && !e.message.includes("SPDX")) console.warn(e.formattedMessage);
  if (errors.length) {
    for (const e of errors) console.error(e.formattedMessage);
    process.exit(1);
  }
  return output.contracts;
}

function save(contracts, names) {
  mkdirSync(outDir, { recursive: true });
  for (const unit of Object.values(contracts)) {
    for (const [name, c] of Object.entries(unit)) {
      if (!names.includes(name)) continue;
      const artifact = {
        abi: c.abi,
        bytecode: `0x${c.evm.bytecode.object}`,
        deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
        linkReferences: c.evm.bytecode.linkReferences,
        deployedSize: c.evm.deployedBytecode.object.length / 2,
      };
      writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify(artifact, null, 2) + "\n");
      console.log(`${name}: ${artifact.deployedSize} bytes deployed`);
    }
  }
}

console.log(`solc ${solc.version()}`);
save(
  compile(
    { "src/GhostPool.sol": path.join(root, "contracts/src/GhostPool.sol") },
    { viaIR: true, optimizer: { enabled: true, runs: 200 } },
  ),
  ["GhostPool"],
);
// The Poseidon library is linked, not inlined. Through via-IR its unrolled assembly grows past the
// 24 KB code size limit (29 KB); the legacy pipeline with the optimizer keeps it at 16 KB.
save(
  compile(
    { "poseidon-solidity/PoseidonT3.sol": path.join(root, "node_modules/poseidon-solidity/PoseidonT3.sol") },
    { optimizer: { enabled: true, runs: 200 } },
  ),
  ["PoseidonT3"],
);

// The app and the scripts import the pool's ABI as a typed constant.
const poolAbi = JSON.parse(readFileSync(path.join(outDir, "GhostPool.json"), "utf8")).abi;
writeFileSync(
  path.join(root, "app/src/lib/abi.generated.ts"),
  `// @generated by scripts/compile.mjs from contracts/out/GhostPool.json\nexport const ghostPoolAbi = ${JSON.stringify(poolAbi, null, 2)} as const;\n`,
);

const verifierSource = path.join(root, "circuits/build/GhostVerifier.sol");
if (existsSync(verifierSource)) {
  // Same as snark-verifier's own `solc --bin`: no optimizer; the verifier is hand-scheduled assembly.
  // The generator pins an exact older pragma; the code itself is plain assembly that 0.8.28 accepts.
  const contracts = compile({ "GhostVerifier.sol": verifierSource }, {}, (source) =>
    source.replace(/pragma solidity [^;]+;/, "pragma solidity ^0.8.19;"),
  );
  const names = Object.keys(contracts["GhostVerifier.sol"]);
  save(contracts, names);
  if (names.length === 1 && names[0] !== "GhostVerifier") {
    // Keep a stable artifact name whatever the generator calls the contract.
    const artifact = readFileSync(path.join(outDir, `${names[0]}.json`));
    writeFileSync(path.join(outDir, "GhostVerifier.json"), artifact);
  }
} else {
  console.log("skipping the verifier: run ghost-cli setup first");
}
