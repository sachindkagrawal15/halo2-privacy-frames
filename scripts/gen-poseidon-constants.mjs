// Emits circomlib's Poseidon constants for t = 3 (two inputs) as Rust, so the Halo2 circuit hashes
// exactly like poseidon-lite in the browser and poseidon-solidity on chain. Also emits test vectors.
//
//   node scripts/gen-poseidon-constants.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { poseidon2 } from "poseidon-lite";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// poseidon-lite's package exports hide the constants module, so load the file directly.
const raw = require(path.join(root, "node_modules/poseidon-lite/constants/2.js")).default;
const decode = (b64) => BigInt("0x" + Buffer.from(b64, "base64").toString("hex"));
const C = raw.C.map(decode);
const M = raw.M.map((row) => row.map(decode));
if (C.length !== 195 || M.length !== 3) throw new Error(`unexpected sizes C=${C.length} M=${M.length}`);

const hex = (x) => `"0x${x.toString(16).padStart(64, "0")}"`;
const rust = `// @generated by scripts/gen-poseidon-constants.mjs from poseidon-lite (circomlib parameters).
// Poseidon over BN254, t = 3, 8 full rounds, 57 partial rounds, x^5 S-box.

pub const ROUND_CONSTANTS: [&str; 195] = [
${C.map((c) => `    ${hex(c)},`).join("\n")}
];

pub const MDS: [[&str; 3]; 3] = [
${M.map((row) => `    [${row.map(hex).join(", ")}],`).join("\n")}
];
`;
writeFileSync(path.join(root, "circuits/ghost-circuit/src/poseidon_constants.rs"), rust);

// Test vectors: the first is circomlib's published Poseidon([1, 2]).
const pairs = [
  [1n, 2n],
  [0n, 0n],
  [123456789n, 987654321n],
  [21888242871839275222246405745257275088548364400416034343698204186575808495616n, 7n],
];
const vectors = pairs.map(([a, b]) => ({ a: a.toString(), b: b.toString(), out: poseidon2([a, b]).toString() }));
writeFileSync(
  path.join(root, "circuits/ghost-circuit/src/poseidon_vectors.json"),
  JSON.stringify(vectors, null, 2) + "\n",
);
console.log("poseidon2([1,2]) =", "0x" + poseidon2([1n, 2n]).toString(16));
